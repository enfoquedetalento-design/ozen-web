-- 1) Operaciones EXTERNAS: todo lo que tiene que ver con un cliente
--    (arreglo, marcación, garantía, traslado, pedido). Una fila = una orden.
--    Los ids de usuario y de tienda van como texto y sin relación a "usuarios" /
--    "tiendas" a propósito (igual que en capacitaciones y permisos): así borrar o
--    desactivar un usuario o una tienda nunca borra ni bloquea una orden.
create table if not exists operaciones_externas (
  id                      uuid primary key default gen_random_uuid(),
  numero                  integer generated by default as identity (start with 1802) unique,
  created_at              timestamptz not null default now(),
  fecha                   date not null,
  tipo                    text not null check (tipo in ('arreglo','marcacion','garantia','traslado','pedido')),
  tienda_id               text not null,          -- tienda que atiende al cliente (en traslados: la que pide la pieza)
  tienda_origen_id        text,                   -- solo traslados: tienda que envía la pieza
  asesor_id               text,                   -- quién recibió al cliente
  asesor_nombre           text,
  registrado_por          text,                   -- cuenta desde la que se creó (puede ser la cuenta de tienda)
  registrado_por_id       text,
  cliente_nombre          text not null,
  cliente_telefono        text,
  descripcion             text not null,
  valor                   numeric not null default 0,
  estado_pago             text not null default 'debe' check (estado_pago in ('pago','debe','no_aplica')),
  venta_id                uuid,                   -- se llenará cuando el cobro se enlace con Registrar venta (parte 4)
  fecha_estimada_entrega  date,
  etapa                   text not null check (etapa in ('recibida','en_gestion','lista','solicitado','enviado','recibido','llego','entregada','cancelada')),
  etapa_desde             timestamptz not null default now(),  -- desde cuándo está en la etapa actual (para las alertas de atraso)
  cerrada_en              timestamptz,            -- cuándo quedó entregada o cancelada
  garantia_decision       text check (garantia_decision in ('cubre','no_cubre')),
  garantia_respuesta      text,
  garantia_decidida_por   text,
  garantia_decidida_en    timestamptz,
  cancelada_motivo        text,
  historial               jsonb not null default '[]'::jsonb  -- cada movimiento: qué pasó, cuándo y quién
);
create index if not exists operaciones_externas_etapa_idx   on operaciones_externas (etapa);
create index if not exists operaciones_externas_fecha_idx   on operaciones_externas (fecha desc);
create index if not exists operaciones_externas_tienda_idx  on operaciones_externas (tienda_id);

-- 2) Operaciones INTERNAS: lo que la tienda necesita y NO tiene que ver con clientes
--    (insumos, novedades, arreglos del inventario, arreglos del punto).
--    Toda solicitud nace como 'nueva', así ninguna queda sin estado.
--    (La pantalla de Internas es la parte 2; la tabla se crea de una vez para no
--    tener que correr otro archivo después.)
create table if not exists operaciones_internas (
  id                    uuid primary key default gen_random_uuid(),
  created_at            timestamptz not null default now(),
  fecha                 date not null,
  tipo                  text not null check (tipo in ('insumos','novedad','arreglo_inventario','arreglo_punto')),
  tienda_id             text not null,            -- id de la tienda, o 'global' si aplica a todas
  reportado_por_id      text,
  reportado_por_nombre  text,
  registrado_por        text,
  registrado_por_id     text,
  descripcion           text not null,
  estado                text not null default 'nueva' check (estado in ('nueva','en_gestion','completada','rechazada')),
  estado_desde          timestamptz not null default now(),
  respuesta             text,                     -- observación del líder, o motivo del rechazo
  gestionado_por        text,
  cerrada_en            timestamptz,
  historial             jsonb not null default '[]'::jsonb
);
create index if not exists operaciones_internas_estado_idx  on operaciones_internas (estado);
create index if not exists operaciones_internas_fecha_idx   on operaciones_internas (fecha desc);

-- 3) Ajustes del módulo. Por ahora una sola fila: quién es el líder de Operaciones
--    (clave 'lider_usuario_id'). Lo elige Master desde la app.
create table if not exists operaciones_config (
  clave            text primary key,
  valor            text,
  actualizado_por  text,
  actualizado_en   timestamptz not null default now()
);

-- 4) Acceso desde la app (mismo esquema que el resto de tablas del proyecto).
--    A propósito NO hay permiso de borrar en externas ni internas: una orden no se
--    borra, se cancela (queda el rastro de quién y por qué).
alter table operaciones_externas  enable row level security;
alter table operaciones_internas  enable row level security;
alter table operaciones_config    enable row level security;

drop policy if exists "op_externas_leer"     on operaciones_externas;
drop policy if exists "op_externas_agregar"  on operaciones_externas;
drop policy if exists "op_externas_cambiar"  on operaciones_externas;
drop policy if exists "op_internas_leer"     on operaciones_internas;
drop policy if exists "op_internas_agregar"  on operaciones_internas;
drop policy if exists "op_internas_cambiar"  on operaciones_internas;
drop policy if exists "op_config_todo"       on operaciones_config;

create policy "op_externas_leer"     on operaciones_externas for select to anon, authenticated using (true);
create policy "op_externas_agregar"  on operaciones_externas for insert to anon, authenticated with check (true);
create policy "op_externas_cambiar"  on operaciones_externas for update to anon, authenticated using (true) with check (true);
create policy "op_internas_leer"     on operaciones_internas for select to anon, authenticated using (true);
create policy "op_internas_agregar"  on operaciones_internas for insert to anon, authenticated with check (true);
create policy "op_internas_cambiar"  on operaciones_internas for update to anon, authenticated using (true) with check (true);
create policy "op_config_todo"       on operaciones_config   for all    to anon, authenticated using (true) with check (true);
